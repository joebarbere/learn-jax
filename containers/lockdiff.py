"""Helper for containers/lock.sh, run inside a base image (stdlib only).

    python3 lockdiff.py freeze                         → name==version for every installed package
    python3 lockdiff.py hold REQ BEFORE                → BEFORE minus the packages REQ pins by name
    python3 lockdiff.py write REQ OUT BEFORE AFTER     → the lockfile: packages added, or moved on purpose
"""
import importlib.metadata as md
import os
import re
import sys


def canon(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def read(path: str) -> dict[str, str]:
    return dict(line.split("==", 1) for line in open(path).read().split())


def asked(req: str) -> set[str]:
    names = set()
    for line in open(req):
        line = line.split("#", 1)[0].strip()
        if line:
            names.add(canon(re.split(r"[=<>~!\[ ;]", line, maxsplit=1)[0]))
    return names


cmd, *args = sys.argv[1:]
if cmd == "freeze":
    print("\n".join(sorted({f"{canon(d.metadata['Name'])}=={d.version}" for d in md.distributions()})))
elif cmd == "hold":
    req, before = args
    keep = asked(req)
    print("\n".join(f"{n}=={v}" for n, v in read(before).items() if n not in keep))
elif cmd == "write":
    req, out, before_p, after_p = args
    before, after, wanted = read(before_p), read(after_p), asked(req)
    moved = sorted(n for n in before if after.get(n) != before[n])
    if bad := [n for n in moved if n not in wanted]:
        sys.exit(f"base packages changed that {req} doesn't pin: {bad}")
    lock = sorted(n for n in after if n not in before or n in moved)
    base, uv, newer = os.environ["BASE"], os.environ["UV_VERSION"], os.environ.get("UV_EXCLUDE_NEWER")
    with open(out, "w") as f:
        f.write(f"# Generated by containers/lock.sh from {os.path.basename(req)} with uv {uv}"
                + (f" (exclude-newer {newer})" if newer else "") + ",\n")
        f.write(f"# resolved inside {base}.\n")
        f.write("# Every package the image adds to its base, pinned; the image installs them with --no-deps.\n")
        f.write(f"# Do not edit: change {os.path.basename(req)} and run `make lock`.\n")
        for n in moved:
            f.write(f"# Replaces the base image's {n}=={before[n]}, because {os.path.basename(req)} pins it.\n")
        f.writelines(f"{n}=={after[n]}\n" for n in lock)
    print(f"[{len(lock)} packages pinned, {len(moved)} replacing base versions, "
          f"{len(before) - len(moved)} base packages unchanged]")
else:
    sys.exit(__doc__)
