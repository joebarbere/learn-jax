"""Write docs/ROSETTA.md (math ↔ Python ↔ NumPy ↔ JAX ↔ PyTorch) from learnjax/rosetta/ (entries + guide.md).

    containers/run.sh python tools/gen_rosetta.py    # `make rosetta`; needs NumPy, not a GPU
"""
import re
from pathlib import Path

from learnjax import rosetta as R

ROOT = Path(__file__).resolve().parent.parent


def anchor(name: str) -> str:
    return re.sub(r"[^a-z0-9 -]", "", name.lower()).replace(" ", "-")


def entry_md(e) -> str:
    where = f"Module {e.module}" + (f"; also {', '.join(e.also)}" if e.also else "")
    out = [f"### {e.name}", "", f"*{where}.*", "", R.math_md(e).replace(f"**{e.name}.** ", "", 1), ""]
    for v in R.VARIANTS:
        if getattr(e, v):
            out += [f"**{R.LABELS[v]}**", "", R.code_block(e, v), ""]
    if e.notes:
        out += ["**Where they differ**", "", R.notes_md(e), ""]
    return "\n".join(out)


def main() -> None:
    lines = ["# Math ↔ code: the Rosetta",
             "",
             "<!-- Generated by tools/gen_rosetta.py from learnjax/rosetta/; edit the registry, not this file. -->",
             "",
             ("Each operation the course introduces, written five ways: the formula (and how papers write it), "
             "plain Python loops (the formula read literally), NumPy, JAX and PyTorch. Every version is run on "
             "the same inputs and checked to agree (`tests/test_rosetta.py`). In the lessons each entry appears "
             "as tabs where the operation is first taught."),
             ""]
    for topic in R.TOPICS:
        es = [e for e in R.ENTRIES if e.topic == topic]
        if es:
            lines.append(f"- **{topic}:** " + ", ".join(f"[{e.name}](#{anchor(e.name)})" for e in es))
    lines += ["", (ROOT / "learnjax" / "rosetta" / "guide.md").read_text().strip(), ""]
    for topic in R.TOPICS:
        es = [e for e in R.ENTRIES if e.topic == topic]
        if es:
            lines += [f"## {topic}", ""] + [entry_md(e) for e in es]
    lines += ["## Index by JAX name", "",
              ("Every JAX, optax and Flax name the lessons use for math, and the entry that explains it. Names that "
              "are plumbing rather than math (devices, dtypes, sharding setup, pytree utilities) are listed in "
              "`learnjax/rosetta/coverage.py` with what they are instead."), "",
              "| name | entry |", "|---|---|"]
    by_api = sorted((a, e.name) for e in R.ENTRIES for a in e.apis)
    lines += [f"| `{a}` | [{n}](#{anchor(n)}) |" for a, n in by_api] + [""]
    (ROOT / "docs" / "ROSETTA.md").write_text("\n".join(lines).rstrip() + "\n")
    print(f"docs/ROSETTA.md: {len(R.ENTRIES)} entries")


if __name__ == "__main__":
    main()
